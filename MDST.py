# SPEED SETTINGS
HEADLESS = True  # Setting to True hides the GUI and speeds up performance
NAV_TIMEOUT_MS = 60_000
USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"


@dataclass(slots=True)
class ProductRow:
    asin: str
    url: str
def intercept_route(route):
    """Prevents images, css, and fonts from loading to save bandwidth and time."""
    if route.request.resource_type in ["image", "stylesheet", "font", "media"]:
        route.abort()
    else:
        route.continue_()



def verify_location(page: Page) -> bool:
    print(f">>> Verifying location...")
    try:
        page.goto(AMAZON_BASE, wait_until="domcontentloaded", timeout=NAV_TIMEOUT_MS)
        loc_text = page.locator("#glow-ingress-line2").inner_text(timeout=5000)
        return TARGET_ZIP in loc_text
    except:
        return False


def scrape_keyword(page: Page, keyword: str) -> list[ProductRow]:
    all_rows = []
    current_page = 1
    search_url = f"{AMAZON_BASE}/s?k={keyword.replace(' ', '+')}"

    while True:
        try:
            # Using 'domcontentloaded' is much faster than 'load'
            page.goto(search_url, wait_until="domcontentloaded", timeout=NAV_TIMEOUT_MS)

            # Check for bot detection - even in headless we need to be careful
            if "captcha" in page.content().lower():
                print(f"   [!] Captcha detected on page {current_page}. Consider reducing speed.")
                break

            # Quickly scroll to bottom to ensure data-asins are rendered
            page.evaluate("window.scrollTo(0, document.body.scrollHeight);")

            soup = BeautifulSoup(page.content(), "html.parser")
            cards = soup.find_all('div', {'data-asin': True})

            page_asins = 0
            for card in cards:
                asin = card.get("data-asin", "").strip()
                if len(asin) == 10:
                    all_rows.append(ProductRow(asin=asin, url=f"{AMAZON_BASE}/dp/{asin}"))
                    page_asins += 1

            print(f"   [Page {current_page}] Found {page_asins} items.")

            next_btn = soup.select_one('a.s-pagination-next')
            if not next_btn or 's-pagination-disabled' in next_btn.get('class', []):
                break

            search_url = AMAZON_BASE + next_btn.get('href')
            current_page += 1

            # Minor delay to prevent instant IP bans
            time.sleep(random.uniform(1, 2))

        except Exception as e:
            print(f"   [!] Finished keyword at page {current_page}.")
            break

    return all_rows


def save_data(keyword: str, rows: list[ProductRow]):
    unique_map = {r.asin: r.url for r in rows if r.asin}
    if not unique_map: return

    clean_name = re.sub(r"[\\/:*?\"<>|]+", "_", keyword).strip()
    file_path = OUTPUT_DIR / f"{clean_name}.csv"

    with open(file_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["Product Links", "Amazon ASINS"])
        for asin, url in unique_map.items():
            writer.writerow([url, asin])
    print(f">>> SAVED: {len(unique_map)} ASINs.")


def main():
    print("Launching Turbo Scraper (Headless)...")
    with sync_playwright() as p:
        context = p.chromium.launch_persistent_context(
            user_data_dir=USER_DATA_DIR,
            headless=HEADLESS,
            user_agent=USER_AGENT,
        )
        page = context.pages[0]

        # ACTIVATE RESOURCE BLOCKING
        page.route("**/*", intercept_route)

        if not verify_location(page):
            print(f"\n[!] ALERT: Target Zip {TARGET_ZIP} not detected.")
            print("Switching to GUI mode for 30 seconds so you can set it...")
            # We can't easily switch headless mid-run, so we advise running once with HEADLESS=False
            # to save the session, then HEADLESS=True forever after.

        for idx, kw in enumerate(KEYWORDS_PASTED, 1):
            print(f"\n[{idx}/{len(KEYWORDS_PASTED)}] Scraping: {kw}")
            results = scrape_keyword(page, kw)
            save_data(kw, results)

        context.close()
    print("\n[COMPLETE]")


if __name__ == "__main__":
    main()